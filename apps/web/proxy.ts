/**
 * Per-request CSP nonce. Scripts run only with the nonce (strict-dynamic); styles allow
 * inline attributes because charts and meters set widths with style props. The engine's
 * WebSocket is same-origin in production (nginx /ws); ENGINE_WS_PUBLIC overrides it in
 * development.
 */
import { NextResponse, type NextRequest } from "next/server";

export function proxy(request: NextRequest) {
  const nonce = Buffer.from(crypto.randomUUID()).toString("base64");
  const dev = process.env.NODE_ENV === "development";
  const wsExtra = process.env.ENGINE_WS_PUBLIC ? ` ${new URL(process.env.ENGINE_WS_PUBLIC).origin}` : "";
  const csp = [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}' 'strict-dynamic'${dev ? " 'unsafe-eval'" : ""}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' blob: data:",
    "font-src 'self'",
    "worker-src 'self'",
    "manifest-src 'self'",
    `connect-src 'self'${wsExtra}`,
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join("; ");
  const headers = new Headers(request.headers);
  headers.set("x-nonce", nonce);
  headers.set("Content-Security-Policy", csp);
  const res = NextResponse.next({ request: { headers } });
  res.headers.set("Content-Security-Policy", csp);
  return res;
}

export const config = {
  matcher: [
    {
      source: "/((?!api|_next/static|_next/image|favicon|icon|apple-touch-icon|card.png|manifest.webmanifest|sw.js).*)",
      missing: [
        { type: "header", key: "next-router-prefetch" },
        { type: "header", key: "purpose", value: "prefetch" },
      ],
    },
  ],
};
